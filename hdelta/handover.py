def suite_table(run_dirs: List[Path], suffix: str = "") -> str:
    rows = ["| run | cadence | phase | rule | deliberate t50 [CI] | compiled t50 [CI] | lead | compiled acc at delib 0.5 | delib acc at compiled onset | t_H | median lag [CI] (n) | lag >0/<0/=0 | sign p | acquired delib/compiled/both | loops to compiled t50 | old-rule peak | old delib path < 0.5 at |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for d in run_dirs:
        p = Path(d) / f"handover{suffix}.json"
        if not p.exists():
            rows.append(f"| {Path(d).name} | (no analysis) |" + " |" * 13)
            continue
        res = json.loads(p.read_text(encoding="utf-8"))
        if "error" in res:
            rows.append(f"| {res['run']} | {res['error']} |" + " |" * 13)
            continue
        for e in res["phases"]:
            l = e["learning"]
            if "error" in l:
                continue
            c, a = l["crossings"], l["acquisition"]
            sw = e.get("switch", {})
            ps_key = "prev_slow_gen" if "prev_slow_gen" in sw else "prev_slow"
            rows.append("| {run} | {cad} | {ph} | {r} | {s50} | {d50} | {lead} | {cat} | {dao} | {th} | {lag} | {pos}/{neg}/{zero} | {p} | {as_}/{ad}/{ab} | {loops} | {peak} | {ps} |".format(
                run=res["run"], cad=res.get("view_cadence") or res.get("probe_every"), ph=e["phase"], r=e["rule"],
                s50=_ci(c.get(f"{l['anchor']}_t50")), d50=_ci(c["direct_t50"]),
                lead=_f(l["lead_t50"]),
                cat=_f(l.get("compiled_at_deliberate_t50"), 2),
                dao=(f"{l['deliberate_at_compiled_onset']:.2f}" if l.get("deliberate_at_compiled_onset") is not None else "never"),
                th=_f(l["t_handover"]), lag=_lag(a), pos=a["lag_positive"], neg=a["lag_negative"], zero=a["lag_zero"],
                p=_f(a["sign_test_p_direct_after_slow"], 3),
                as_=a["slow_acquired"], ad=a["direct_acquired"], ab=a["both_acquired"],
                loops=_f(l["consolidation_supply"]["loops_to_direct_t50"]),
                peak=_f(sw.get("old_rule_peak"), 2) if sw else "-", ps=_f(sw.get(f"{ps_key}_t_below_50")) if sw else "-"))
    return "\n".join(rows)


def aggregate_seeds(run_dirs: List[Path], out_dir: Path, name: str = "full") -> dict:
    """Pool the per-puzzle lags of several seeds of the same config; report per-seed and pooled statistics."""
    rng = np.random.default_rng(0)
    results = [json.loads((Path(d) / "handover.json").read_text(encoding="utf-8")) for d in run_dirs
               if (Path(d) / "handover.json").exists()]
    results = [r for r in results if "error" not in r]
    agg: Dict[str, object] = {"config": name, "seeds": [r.get("seed", 0) for r in results], "phases": []}
    n_ph = min(len(r["phases"]) for r in results) if results else 0
    for i in range(n_ph):
        per_seed, pooled = [], []
        rule = results[0]["phases"][i]["rule"]
        for r in results:
            l = r["phases"][i]["learning"]
            if "error" in l:
                continue
            a = l["acquisition"]
            per_seed.append({"seed": r.get("seed", 0),
                             "deliberate_t50": l["crossings"].get(f"{l['anchor']}_t50", {}).get("point"),
                             "compiled_t50": l["crossings"]["direct_t50"]["point"],
                             "compiled_t80": l["crossings"]["direct_t80"]["point"],
                             "t_handover": l["t_handover"], "lead_t50": l["lead_t50"],
                             "median_lag": a["lag"]["median"] if a["lag"] else None, "n_lag": len(a["lag_values"]),
                             "compiled_at_deliberate_t50": l.get("compiled_at_deliberate_t50"),
                             "deliberate_at_compiled_onset": l.get("deliberate_at_compiled_onset"),
                             "sign_p": a["sign_test_p_direct_after_slow"],
                             "loops_to_t50": l["consolidation_supply"]["loops_to_direct_t50"]})
            pooled += a["lag_values"]
        pooled = np.array(pooled, dtype=float)
        pos, neg, p = sign_test(pooled) if len(pooled) else (0, 0, float("nan"))
        def _msd(key):
            v = [s[key] for s in per_seed if s[key] is not None]
            return {"mean": float(np.mean(v)), "sd": float(np.std(v, ddof=1)) if len(v) > 1 else 0.0, "n": len(v)} if v else None
        agg["phases"].append({"phase": i, "rule": rule, "per_seed": per_seed,
                              "pooled_lag": boot_median(pooled, rng) if len(pooled) else None,
                              "pooled_sign": {"positive": pos, "negative": neg, "p": p},
                              "deliberate_t50": _msd("deliberate_t50"), "compiled_t50": _msd("compiled_t50"),
                              "compiled_t80": _msd("compiled_t80"), "t_handover": _msd("t_handover"),
                              "lead_t50": _msd("lead_t50"), "median_lag": _msd("median_lag"),
                              "compiled_at_deliberate_t50": _msd("compiled_at_deliberate_t50"),
                              "deliberate_at_compiled_onset": _msd("deliberate_at_compiled_onset"),
                              "loops_to_t50": _msd("loops_to_t50")})
    out_dir = Path(out_dir)
    (out_dir / f"handover_seeds_{name}.json").write_text(json.dumps(agg, indent=1), encoding="utf-8")
    L = [f"# Seed aggregation: {name} (seeds {agg['seeds']})", "",
         "| phase | rule | deliberate t50 mean ± sd | compiled t50 mean ± sd | compiled t80 mean ± sd | lead at 0.5 mean ± sd | compiled acc at delib 0.5 | delib acc at compiled onset | t_H mean ± sd | per-seed median lags | pooled median lag [CI] (n) | pooled sign test +/- (p) | loops to compiled t50 mean ± sd |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    def _ms(d):
        return "n/a" if not d else f"{d['mean']:.0f} ± {d['sd']:.0f} (n={d['n']})"
    for ph in agg["phases"]:
        def _ms2(d):
            return "n/a" if not d else f"{d['mean']:.2f} +- {d['sd']:.2f} (n={d['n']})"
        L.append("| {ph} | {r} | {d50} | {c50} | {c80} | {lead} | {cat} | {dao} | {th} | {seeds} | {pool} | {sg} | {loops} |".format(
            ph=ph["phase"], r=ph["rule"], d50=_ms(ph["deliberate_t50"]), c50=_ms(ph["compiled_t50"]), c80=_ms(ph["compiled_t80"]),
            lead=_ms(ph["lead_t50"]), cat=_ms2(ph["compiled_at_deliberate_t50"]), dao=_ms2(ph["deliberate_at_compiled_onset"]),
            th=_ms(ph["t_handover"]),
            seeds=", ".join(f"s{s['seed']}: {_f(s['median_lag'])} (n={s['n_lag']}, p={_f(s['sign_p'], 3)})" for s in ph["per_seed"]),
            pool=_lag({"lag": ph["pooled_lag"]}), sg=f"{ph['pooled_sign']['positive']}/{ph['pooled_sign']['negative']} (p={_f(ph['pooled_sign']['p'], 4)})",
            loops=_ms(ph["loops_to_t50"])))
    (out_dir / f"handover_seeds_{name}.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    return agg


