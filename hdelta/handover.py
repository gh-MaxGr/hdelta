"""Hand-over analysis: puzzle-level tracking of the deliberate and the compiled path.

Inputs (per run directory):
    probes.jsonl   every probe carries ``per_puzzle[rule]`` with 0/1 outcomes for the
                   fixed held-out puzzles on each path, plus the rule each compiled
                   answer followed (``attrib``) and ``cum_consolidated`` (verified loops
                   written since the phase started)
    config.json

Outputs: handover.json, handover.md, handover.png  (plus *_c40 variants for the
synthetic cadence-40 view, and handover_seeds.* for multi-seed aggregation)

Paths tracked per puzzle:
    slow_gen   rule stated + worked examples + scratchpad, GENERATED by the model
               (the primary anchor: proves the model used the crutch)
    slow       the same, teacher-forced exact match (secondary: proves capacity)
    direct     input only, greedy generation                     (the compiled reflex)
    free       open-ended after "Input: x"                       (instant answer)

Statistics per learning phase (rule R active), anchor = slow_gen when logged:
    * population curves with Wilson 95 % intervals
    * crossing times at 0.5 and 0.8 for every path, with bootstrap 95 % intervals over
      puzzles (1000 resamples) and the share of resamples that never cross
    * crossing point t_H: first probe where the compiled path is at least as accurate as
      the anchor while being >= 0.5; lead area = mean over the phase of max(anchor - direct, 0)
    * joint-state occupancy (neither / slow-only / both / direct-only) at every probe
    * per-puzzle acquisition times (correct on ``persist`` consecutive probes), the
      per-puzzle lag compiled - anchor, its median with bootstrap CI, a one-sided sign
      test of "compiled follows deliberate"; censoring reported.  The same is computed
      against the teacher-forced slow path as ``acquisition_tf``.
    * consolidation supply: verified loops written when the compiled path crosses 0.5 / 0.8
    * data quality: agreement between generated and teacher-forced compiled scoring
Statistics per switch phase (rule R replaces P):
    * share of compiled answers still following P, with Wilson CI, time to <= 0.1
    * per-puzzle time at which the old-rule answer disappears (among puzzles that started with it)
    * the old rule's own slow and compiled paths over the phase (interference)
"""
from __future__ import annotations

import json
import math
from pathlib import Path
from typing import Dict, List, Optional

import numpy as np

PERSIST = 2          # consecutive probes required for "acquired"
BOOT = 1000
TAG_ORDER = {"baseline": 0, "stream": 0, "pre_rem": 0, "post_rem": 1, "final": 2}


# ----------------------------------------------------------------------------- utils
def wilson(k: float, n: int, z: float = 1.96):
    if n == 0:
        return (float("nan"), float("nan"))
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0.0, c - h), min(1.0, c + h))


def crossing(curve, t_rel, thr) -> Optional[float]:
    for k, v in enumerate(curve):
        if v >= thr:
            return float(t_rel[k])
    return None


def boot_crossing(M: np.ndarray, t_rel, thr: float, rng: np.random.Generator):
    n = M.shape[1]
    vals = []
    for _ in range(BOOT):
        idx = rng.integers(0, n, n)
        x = crossing(M[:, idx].mean(1), t_rel, thr)
        vals.append(np.nan if x is None else x)
    vals = np.array(vals, dtype=float)
    never = float(np.isnan(vals).mean())
    if np.all(np.isnan(vals)):
        return {"lo": None, "hi": None, "p_never": never}
    return {"lo": float(np.nanpercentile(vals, 2.5)), "hi": float(np.nanpercentile(vals, 97.5)), "p_never": never}


def acquisition(M: np.ndarray, t_rel, persist: int = PERSIST) -> np.ndarray:
    """Per puzzle: first t_rel at which the path is correct on `persist` consecutive probes."""
    K, n = M.shape
    out = np.full(n, np.nan)
    for i in range(n):
        col = M[:, i]
        for k in range(K - persist + 1):
            if col[k:k + persist].all():
                out[i] = t_rel[k]
                break
    return out


def sign_test(lags: np.ndarray):
    pos = int((lags > 0).sum())
    neg = int((lags < 0).sum())
    m = pos + neg
    p = sum(math.comb(m, k) for k in range(pos, m + 1)) / 2 ** m if m else float("nan")
    return pos, neg, p


def boot_median(x: np.ndarray, rng: np.random.Generator):
    if len(x) == 0:
        return None
    meds = [float(np.median(rng.choice(x, len(x)))) for _ in range(BOOT)]
    return {"median": float(np.median(x)), "lo": float(np.percentile(meds, 2.5)),
            "hi": float(np.percentile(meds, 97.5)), "n": int(len(x))}


def lag_stats(A: np.ndarray, D: np.ndarray, t_rel, rng) -> dict:
    a_s = acquisition(A, t_rel)
    a_d = acquisition(D, t_rel)
    both = ~np.isnan(a_s) & ~np.isnan(a_d)
    lags = (a_d - a_s)[both]
    pos, neg, p = sign_test(lags)
    return {
        "persist": PERSIST, "n_puzzles": int(A.shape[1]),
        "slow_acquired": int((~np.isnan(a_s)).sum()),
        "direct_acquired": int((~np.isnan(a_d)).sum()),
        "both_acquired": int(both.sum()),
        "slow_median_t": None if np.all(np.isnan(a_s)) else float(np.nanmedian(a_s)),
        "direct_median_t": None if np.all(np.isnan(a_d)) else float(np.nanmedian(a_d)),
        "lag": boot_median(lags, rng),
        "lag_values": [float(v) for v in lags],
        "lag_positive": pos, "lag_negative": neg, "lag_zero": int((lags == 0).sum()),
        "sign_test_p_direct_after_slow": p,
    }


# ----------------------------------------------------------------------------- data
def load_run(run_dir: Path):
    run_dir = Path(run_dir)
    lines = [json.loads(l) for l in (run_dir / "probes.jsonl").read_text(encoding="utf-8").splitlines() if l.strip()]
    probes = [r for r in lines if "metrics" in r and r.get("per_puzzle")]
    cfg = json.loads((run_dir / "config.json").read_text(encoding="utf-8"))
    return probes, cfg


def phase_probes(probes: List[dict], phase_idx: int, phase_start: int, cadence: Optional[int] = None) -> List[dict]:
    sel = [r for r in probes if r["phase"] == phase_idx]
    start = [r for r in probes if r["t"] == phase_start and r["phase"] != phase_idx]
    if start:
        s = dict(start[-1])
        s["_is_start"] = True
        sel = [s] + sel
    if cadence:   # synthetic coarser cadence: keep probes on the coarser grid
        sel = [r for r in sel if (r["t"] - phase_start) % cadence == 0]
    sel.sort(key=lambda r: (r["t"], TAG_ORDER.get(r["tag"], 0)))
    return sel


def matrix(recs: List[dict], rule: str, key: str) -> Optional[np.ndarray]:
    rows = [r["per_puzzle"].get(rule, {}).get(key) for r in recs]
    if not rows or any(x is None for x in rows):
        return None
    n = min(len(x) for x in rows)
    if n == 0:
        return None
    return np.array([x[:n] for x in rows], dtype=np.int8)


def curve(M: np.ndarray):
    n = M.shape[1]
    means = M.mean(1)
    ci = [wilson(float(M[k].sum()), n) for k in range(M.shape[0])]
    return {"mean": [float(v) for v in means], "lo": [c[0] for c in ci], "hi": [c[1] for c in ci], "n": int(n)}


# ----------------------------------------------------------------------------- analyses
def analyse_learning(recs: List[dict], rule: str, phase_start: int, rng: np.random.Generator) -> dict:
    t_rel = [r["t"] - phase_start for r in recs]
    S = matrix(recs, rule, "slow")
    G = matrix(recs, rule, "slow_gen")
    D = matrix(recs, rule, "direct")
    out: Dict[str, object] = {"rule": rule, "t_rel": t_rel, "n_probes": len(recs),
                              "tags": [r["tag"] for r in recs]}
    if D is None or (S is None and G is None):
        out["error"] = "per-puzzle slow/direct outcomes missing"
        return out
    F = matrix(recs, rule, "free")
    TF = matrix(recs, rule, "direct_tf")
    anchor_key = "slow_gen" if G is not None else "slow"
    A = G if G is not None else S
    out["anchor"] = anchor_key
    n = min(A.shape[1], D.shape[1])
    A, Dn = A[:, :n], D[:, :n]

    out["curves"] = {"direct": curve(D)}
    if S is not None:
        out["curves"]["slow"] = curve(S)
    if G is not None:
        out["curves"]["slow_gen"] = curve(G)
    if F is not None:
        out["curves"]["free"] = curve(F)
    a_mean, d_mean = A.mean(1), Dn.mean(1)

    # crossings with bootstrap intervals, for every logged path
    cross = {}
    for name, M in (("slow", S), ("slow_gen", G), ("direct", D), ("free", F)):
        if M is None:
            continue
        for thr in (0.5, 0.8):
            cross[f"{name}_t{int(thr * 100)}"] = {"point": crossing(M.mean(1), t_rel, thr),
                                                  **boot_crossing(M, t_rel, thr, rng)}
    out["crossings"] = cross
    for thr in (50, 80):
        a, b = cross[f"{anchor_key}_t{thr}"]["point"], cross[f"direct_t{thr}"]["point"]
        out[f"lead_t{thr}"] = None if a is None or b is None else b - a

    # crossing point and lead area (anchor vs compiled)
    t_H = None
    for k in range(len(t_rel)):
        if d_mean[k] >= a_mean[k] and d_mean[k] >= 0.5:
            t_H = float(t_rel[k])
            break
    out["t_handover"] = t_H
    # Onset statistics.  The compiled curve rises steeply and near-synchronously across
    # puzzles, which makes the per-puzzle lag noisy; these two scalars state the ordering
    # claim directly and are robust to that steepness:
    #   "when the reflex first appears, how well was deliberation already doing?"
    #   "when deliberation first worked, had the reflex appeared at all?"
    t_onset = crossing(d_mean, t_rel, 0.1)
    out["t_compiled_onset"] = t_onset
    out["deliberate_at_compiled_onset"] = float(a_mean[t_rel.index(t_onset)]) if t_onset is not None else None
    t_a50 = crossing(a_mean, t_rel, 0.5)
    out["compiled_at_deliberate_t50"] = float(d_mean[t_rel.index(t_a50)]) if t_a50 is not None else None
    out["lead_area"] = float(np.mean(np.clip(a_mean - d_mean, 0, None)))
    out["mean_gap_slow_minus_direct"] = float(np.mean(a_mean - d_mean))

    # joint-state occupancy (anchor vs compiled)
    occ = {"neither": [], "slow_only": [], "both": [], "direct_only": []}
    for k in range(len(recs)):
        s, d = A[k].astype(bool), Dn[k].astype(bool)
        occ["both"].append(int((s & d).sum()))
        occ["slow_only"].append(int((s & ~d).sum()))
        occ["direct_only"].append(int((~s & d).sum()))
        occ["neither"].append(int((~s & ~d).sum()))
    out["occupancy"] = occ

    # per-puzzle acquisition and lag: primary (anchor) and secondary (teacher-forced)
    out["acquisition"] = lag_stats(A, Dn, t_rel, rng)
    if S is not None and anchor_key == "slow_gen":
        m = min(S.shape[1], D.shape[1])
        out["acquisition_tf"] = lag_stats(S[:, :m], D[:, :m], t_rel, rng)
    if F is not None:
        a_f = acquisition(F, t_rel)
        out["acquisition"]["free_acquired"] = int((~np.isnan(a_f)).sum())
        out["acquisition"]["free_median_t"] = None if np.all(np.isnan(a_f)) else float(np.nanmedian(a_f))

    # consolidation supply
    cum = [0 if r.get("_is_start") else int(r.get("cum_consolidated", 0)) for r in recs]
    out["cum_consolidated"] = cum
    supply = {}
    for thr in (0.5, 0.8):
        x = crossing(d_mean, t_rel, thr)
        supply[f"loops_to_direct_t{int(thr*100)}"] = None if x is None else cum[t_rel.index(x)]
    out["consolidation_supply"] = supply

    if TF is not None:
        m = min(D.shape[1], TF.shape[1])
        out["direct_gen_vs_tf_agreement"] = float((D[:, :m] == TF[:, :m]).mean())
    return out


def analyse_switch(recs: List[dict], rule: str, prev: str, phase_start: int, rng: np.random.Generator) -> dict:
    t_rel = [r["t"] - phase_start for r in recs]
    out: Dict[str, object] = {"rule": rule, "prev_rule": prev, "t_rel": t_rel}
    attrib = [r["per_puzzle"].get(rule, {}).get("attrib") for r in recs]
    if any(a is None for a in attrib):
        out["error"] = "attribution missing"
        return out
    n = min(len(a) for a in attrib)
    Am = np.array([[1 if x == prev else 0 for x in a[:n]] for a in attrib], dtype=np.int8)
    out["old_rule_share"] = curve(Am)
    share = Am.mean(1)
    out["old_rule_peak"] = float(share.max())
    out["t_old_rule_peak"] = float(t_rel[int(share.argmax())])
    gone = None
    for k in range(int(share.argmax()), len(t_rel)):
        if share[k] <= 0.1:
            gone = float(t_rel[k])
            break
    out["t_old_rule_below_10pct"] = gone
    starters = np.where(Am[0] == 1)[0] if len(Am) else np.array([], dtype=int)
    dis = []
    for i in starters:
        col = Am[:, i]
        t_d = None
        for k in range(len(col) - PERSIST + 1):
            if not col[k:k + PERSIST].any():
                t_d = t_rel[k]
                break
        dis.append(np.nan if t_d is None else t_d)
    dis = np.array(dis, dtype=float)
    out["old_answer_starters"] = int(len(starters))
    out["old_answer_disappearance"] = boot_median(dis[~np.isnan(dis)], rng) if len(dis) else None
    out["old_answer_persisting"] = int(np.isnan(dis).sum()) if len(dis) else 0
    for key, name in (("slow_gen", "prev_slow_gen"), ("slow", "prev_slow"), ("direct", "prev_direct")):
        M = matrix(recs, prev, key)
        if M is not None:
            c = curve(M)
            out[name] = c
            below = None
            if c["mean"][0] >= 0.5:          # only meaningful if the old path was working
                for k, v in enumerate(c["mean"]):
                    if v < 0.5 and k > 0:
                        below = float(t_rel[k])
                        break
            out[f"{name}_start"] = c["mean"][0]
            out[f"{name}_t_below_50"] = below
    return out


def analyse_run(run_dir: Path, seed: int = 0, cadence: Optional[int] = None, suffix: str = "") -> dict:
    """Full analysis of one run.  ``cadence`` keeps only probes on that grid (synthetic
    coarser view) and writes handover<suffix>.{json,md,png}."""
    run_dir = Path(run_dir)
    probes, cfg = load_run(run_dir)
    rng = np.random.default_rng(seed)
    phases = cfg["stream"]["phases"]
    result: Dict[str, object] = {"run": run_dir.name, "seed": cfg.get("seed", 0), "persist": PERSIST,
                                 "bootstrap": BOOT, "probe_every": cfg["stream"].get("probe_every"),
                                 "view_cadence": cadence, "phases": [],
                                 "slow_kind": "rule stated, steps" if cfg["stream"].get("rule_text") else "worked examples, steps"}
    if not probes:
        result["error"] = "no per-puzzle outcomes in probes.jsonl (older run)"
        (run_dir / f"handover{suffix}.json").write_text(json.dumps(result, indent=1), encoding="utf-8")
        return result
    phase_start = {}
    for r in probes:
        if r["phase"] >= 0:
            phase_start.setdefault(r["phase"], r["phase_start"])
    for i, ph in enumerate(phases):
        if i not in phase_start:
            continue
        recs = phase_probes(probes, i, phase_start[i], cadence)
        if len(recs) < 2:
            continue
        rule = ph["rule"]
        prev = None
        for j in range(i - 1, -1, -1):
            if phases[j]["rule"] != rule:
                prev = phases[j]["rule"]
                break
        entry = {"phase": i, "rule": rule, "prev_rule": prev, "puzzles": ph["puzzles"],
                 "learning": analyse_learning(recs, rule, phase_start[i], rng)}
        if prev is not None:
            entry["switch"] = analyse_switch(recs, rule, prev, phase_start[i], rng)
        result["phases"].append(entry)
    (run_dir / f"handover{suffix}.json").write_text(json.dumps(result, indent=1), encoding="utf-8")
    (run_dir / f"handover{suffix}.md").write_text(to_markdown(result), encoding="utf-8")
    try:
        plot_handover(result, run_dir / f"handover{suffix}.png")
    except Exception as e:  # plotting must not break the analysis
        result["plot_error"] = repr(e)
    return result


# ----------------------------------------------------------------------------- report
def _f(v, nd=0):
    if v is None:
        return "never"
    if isinstance(v, float) and math.isnan(v):
        return "n/a"
    return f"{v:.{nd}f}" if isinstance(v, (int, float)) else str(v)


def _ci(c: Optional[dict]) -> str:
    if c is None or c.get("point") is None:
        return "never"
    lo, hi = c.get("lo"), c.get("hi")
    s = f"{c['point']:.0f}"
    if lo is not None and hi is not None:
        s += f" [{lo:.0f}, {hi:.0f}]"
    if c.get("p_never", 0) > 0.05:
        s += f" (never in {100*c['p_never']:.0f}% of resamples)"
    return s


def _lag(a: Optional[dict]) -> str:
    if not a or a.get("lag") is None:
        return "n/a"
    lag = a["lag"]
    return f"{lag['median']:.0f} [{lag['lo']:.0f}, {lag['hi']:.0f}] (n={lag['n']})"


def to_markdown(res: dict) -> str:
    view = f", synthetic cadence {res['view_cadence']}" if res.get("view_cadence") else ""
    L = [f"# Hand-over analysis: {res['run']} (seed {res.get('seed', 0)}, probe cadence {res.get('probe_every')}{view})", "",
         f"Anchor = the model-generated slow path where logged (teacher-forced as secondary). Acquisition = correct on "
         f"{res['persist']} consecutive probes. Intervals: Wilson (curves), bootstrap over puzzles with {res['bootstrap']} "
         f"resamples (crossings, medians). Sign test: one-sided, compiled acquired after deliberate.", ""]
    if "error" in res:
        L.append(f"**{res['error']}**")
        return "\n".join(L)
    L += ["## Learning phases", "",
          "| phase | rule | anchor | deliberate t50 [CI] | compiled t50 [CI] | lead at 0.5 | compiled acc when deliberate hits 0.5 | deliberate acc at compiled onset (0.1) | deliberate t80 | compiled t80 | instant t50 | t_H | lead area | median lag [CI] | lag >0 / <0 / =0 | sign p | acquired delib / compiled / both (of n) | loops at compiled t50 / t80 | tf slow t50 | tf median lag | tf sign p | gen-vs-tf agreement |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for e in res["phases"]:
        l = e["learning"]
        if "error" in l:
            L.append(f"| {e['phase']} | {e['rule']} | {l['error']} |")
            continue
        c, a, s = l["crossings"], l["acquisition"], l["consolidation_supply"]
        tf = l.get("acquisition_tf")
        L.append("| {ph} | {r} | {an} | {s50} | {d50} | {lead} | {cat} | {dao} | {s80} | {d80} | {f50} | {th} | {la:.2f} | {lag} | {pos} / {neg} / {zero} | {p} | {as_} / {ad} / {ab} (of {n}) | {l50} / {l80} | {tfs50} | {tflag} | {tfp} | {agr} |".format(
            ph=e["phase"], r=e["rule"], an=l["anchor"], s50=_ci(c.get(f"{l['anchor']}_t50")), d50=_ci(c["direct_t50"]),
            lead=_f(l["lead_t50"]),
            cat=_f(l.get("compiled_at_deliberate_t50"), 2),
            dao=(f"{l['deliberate_at_compiled_onset']:.2f} (t={l['t_compiled_onset']:.0f})"
                 if l.get("deliberate_at_compiled_onset") is not None else "never"),
            s80=_ci(c.get(f"{l['anchor']}_t80")), d80=_ci(c["direct_t80"]),
            f50=_ci(c.get("free_t50")) if "free_t50" in c else "n/a", th=_f(l["t_handover"]), la=l["lead_area"],
            lag=_lag(a), pos=a["lag_positive"], neg=a["lag_negative"], zero=a["lag_zero"],
            p=_f(a["sign_test_p_direct_after_slow"], 4), as_=a["slow_acquired"], ad=a["direct_acquired"], ab=a["both_acquired"], n=a["n_puzzles"],
            l50=_f(s["loops_to_direct_t50"]), l80=_f(s["loops_to_direct_t80"]),
            tfs50=_ci(c.get("slow_t50")) if "slow_t50" in c else "n/a", tflag=_lag(tf), tfp=_f(tf["sign_test_p_direct_after_slow"], 4) if tf else "n/a",
            agr=_f(l.get("direct_gen_vs_tf_agreement"), 3)))
    L += ["", "Joint-state occupancy at the start / middle / end of each phase (neither, deliberate-only, both, compiled-only):", ""]
    for e in res["phases"]:
        l = e["learning"]
        if "error" in l:
            continue
        o = l["occupancy"]
        K = len(o["both"])
        pts = [0, K // 2, K - 1]
        L.append(f"- phase {e['phase']} ({e['rule']}): " + " -> ".join(
            f"t={l['t_rel'][k]:.0f}: {o['neither'][k]}/{o['slow_only'][k]}/{o['both'][k]}/{o['direct_only'][k]}" for k in pts))
    sw = [e for e in res["phases"] if "switch" in e and "error" not in e["switch"]]
    if sw:
        L += ["", "## Switch phases (unhooking)", "",
              "| phase | new rule | old rule | old-rule answers, peak share (at t) | below 10 % at | puzzles starting with the old answer | median disappearance [CI] | still persisting at end | old rule's generated slow path: start -> < 0.5 at | old rule's compiled path: start -> < 0.5 at |",
              "|---|---|---|---|---|---|---|---|---|---|"]
        for e in sw:
            s = e["switch"]
            d = s.get("old_answer_disappearance")
            d_s = "n/a" if not d else f"{d['median']:.0f} [{d['lo']:.0f}, {d['hi']:.0f}]"
            ps_key = "prev_slow_gen" if "prev_slow_gen" in s else "prev_slow"
            L.append("| {ph} | {r} | {p} | {peak:.2f} (t={tp:.0f}) | {gone} | {st} | {dis} | {pers} | {pss:.2f} -> {ps} | {pds:.2f} -> {pd} |".format(
                ph=e["phase"], r=e["rule"], p=e["prev_rule"], peak=s["old_rule_peak"], tp=s["t_old_rule_peak"],
                gone=_f(s["t_old_rule_below_10pct"]), st=s["old_answer_starters"], dis=d_s, pers=s["old_answer_persisting"],
                pss=s.get(f"{ps_key}_start", float("nan")), ps=_f(s.get(f"{ps_key}_t_below_50")),
                pds=s.get("prev_direct_start", float("nan")), pd=_f(s.get("prev_direct_t_below_50"))))
    return "\n".join(L) + "\n"


def plot_handover(res: dict, out_path: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from .plots import INK, INK2, SERIES, SURFACE  # noqa: F401  (rcParams are set on import)

    phases = [e for e in res["phases"] if "error" not in e["learning"]]
    if not phases:
        return
    fig, axes = plt.subplots(len(phases), 3, figsize=(13, 3.2 * len(phases)), squeeze=False)
    for row, e in zip(axes, phases):
        l = e["learning"]
        t = l["t_rel"]
        ax = row[0]
        series = [(l["anchor"], f"deliberate, {'generated' if l['anchor'] == 'slow_gen' else 'teacher-forced'} ({res.get('slow_kind', 'steps')})"),
                  ("direct", "compiled (input only)"), ("free", "instant, open-ended")]
        for i, (key, label) in enumerate(series):
            if key not in l["curves"]:
                continue
            c = l["curves"][key]
            ax.plot(t, c["mean"], color=SERIES[i], label=label)
            ax.fill_between(t, c["lo"], c["hi"], color=SERIES[i], alpha=0.15, linewidth=0)
        if l["t_handover"] is not None:
            ax.axvline(l["t_handover"], color=INK2, linewidth=0.8, linestyle=(0, (3, 3)))
            ax.text(l["t_handover"], 1.02, "t_H", color=INK2, fontsize=8, ha="center")
        ax.set_ylim(-0.02, 1.08)
        ax.set_ylabel("accuracy (Wilson 95 %)")
        ax.set_title(f"phase {e['phase']}, rule {e['rule']}: the two paths", loc="left", fontsize=10)
        ax.legend(loc="upper left", fontsize=8)
        ax = row[1]
        o = l["occupancy"]
        n = l["acquisition"]["n_puzzles"]
        stack = np.array([o["neither"], o["slow_only"], o["both"], o["direct_only"]], dtype=float) / n
        ax.stackplot(t, stack, labels=["neither", "deliberate-only", "both", "compiled-only"],
                     colors=["#e6e5e1", SERIES[0], SERIES[2], SERIES[1]], alpha=0.9)
        ax.set_ylim(0, 1)
        ax.set_ylabel("fraction of puzzles")
        ax.set_title("joint state of each puzzle", loc="left", fontsize=10)
        ax.legend(loc="center right", fontsize=8)
        ax = row[2]
        lags = l["acquisition"]["lag_values"]
        if lags:
            step = max(1, (t[1] - t[0]) if len(t) > 1 else 1)
            bins = np.arange(min(lags) - step / 2, max(lags) + step, step)
            ax.hist(lags, bins=bins, color=SERIES[2], edgecolor=SURFACE)
            ax.axvline(0, color=INK2, linewidth=0.8)
